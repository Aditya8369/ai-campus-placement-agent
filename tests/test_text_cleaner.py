# 7. IN-MEMORY DEBUGGING RAW TEXT STORAGE
# ==============================================================================

def test_in_memory_raw_text_storage_and_cleanup():
    """
    Verifies that un-normalized raw text is stored in memory for debugging,
    accessible via get_last_raw_resume_text() and get_raw_resume_text(id),
    and cleared via clear_raw_text_cache().
    """
    clear_raw_text_cache()
    assert get_last_raw_resume_text() is None

    raw_input = "ﬁnance and develop-\nment with \uf0b7 C++"
    cleaned = normalize_resume_text(raw_input, store_raw=True, text_id="resume_debug_01")

    # Cleaned text has artifacts normalized
    assert "finance and development with • C++" in cleaned

    # Raw text retained in memory in its original artifact form
    last_raw = get_last_raw_resume_text()
    assert last_raw == raw_input
    assert "ﬁnance" in last_raw
    assert "develop-\nment" in last_raw

    by_id = get_raw_resume_text("resume_debug_01")
    assert by_id == raw_input

    # Clearing memory store
    clear_raw_text_cache()
    assert get_last_raw_resume_text() is None
    assert get_raw_resume_text("resume_debug_01") is None


