"""
Unit tests for Resume Text Artifact Normalization (#645).
=========================================================
Acceptance Criteria:
1. "ﬁnance" and "ﬂow" are matched as "finance" and "flow" (ligature expansion & NFKC).
2. Hyphenated line breaks are joined, while real hyphenated words in a single line stay unchanged.
3. Skill names like C++, C#, .NET and Node.js are preserved exactly.
4. Unit tests cover each artifact type with small samples (bullets, whitespace, repeated headers/footers).
5. In-memory raw text debugging store works without disk persistence.
"""

import pytest
from utils.text_cleaner import (
    normalize_resume_text,
    expand_ligatures,
    join_hyphenated_line_breaks,
    normalize_bullets,
    collapse_whitespace,
    remove_repeated_headers_and_footers,
    get_last_raw_resume_text,
    get_raw_resume_text,
    clear_raw_text_cache,
)
from utils.pdf_reader import normalize_resume_text as pdf_normalize_resume_text


# ==============================================================================
# 1. LIGATURE EXPANSION & UNICODE NFKC NORMALIZATION TESTS
# ==============================================================================

def test_ligature_expansion_finance_and_flow():
    """
    Acceptance criterion: 'ﬁnance' and 'ﬂow' are matched as 'finance' and 'flow'.
    """
    sample = "Experienced in ﬁnance, cash ﬂow modeling, and quantitative analysis."
    result = expand_ligatures(sample)

    assert "finance" in result
    assert "flow" in result
    assert "ﬁ" not in result
    assert "ﬂ" not in result
    assert result == "Experienced in finance, cash flow modeling, and quantitative analysis."


def test_ligature_expansion_other_common_ligatures():
    """Verifies expansion of ff, ffi, ffl, ft, st, and Latin ligatures."""
    sample = "Oﬀline deployment with eﬃcient caching and aﬄuent user proﬁles."
    result = expand_ligatures(sample)

    assert "Offline" in result
    assert "efficient" in result
    assert "affluent" in result
    assert "profiles" in result


def test_unicode_nfkc_normalization():
    """Verifies NFKC compatibility decomposition for fullwidth and compatibility characters."""
    # Fullwidth letters and digits (often generated by Asian typesetting systems)
    fullwidth_sample = "Ｐｙｔｈｏｎ　３．１１　ａｎｄ　ＪａｖａＳｃｒｉｐｔ"
    result = normalize_resume_text(fullwidth_sample, store_raw=False)

    assert "Python 3.11 and JavaScript" == result


# ==============================================================================
# 2. HYPHENATED LINE BREAKS JOINING VS SINGLE-LINE HYPHENS
# ==============================================================================

def test_hyphenated_line_breaks_are_joined():
    """
    Acceptance criterion: Hyphenated line breaks are joined.
    """
    broken_sample = (
        "Led backend develop-\nment of distributed micro-\nservices and "
        "managed imple-\r\n  mentation of secure auth."
    )
    result = join_hyphenated_line_breaks(broken_sample)

    assert "development" in result
    assert "microservices" in result
    assert "implementation" in result
    assert "develop-" not in result
    assert "micro-" not in result
    assert "imple-" not in result


def test_real_single_line_hyphenated_words_stay_unchanged():
    """
    Acceptance criterion: Real hyphenated words in a single line stay unchanged.
    """
    single_line_sample = (
        "Full-stack engineer building object-oriented architectures with "
        "end-to-end testing, cross-functional collaboration, and high-impact deliverables."
    )
    result = join_hyphenated_line_breaks(single_line_sample)

    assert result == single_line_sample
    assert "full-stack" in result.lower()
    assert "object-oriented" in result.lower()
    assert "end-to-end" in result.lower()
    assert "cross-functional" in result.lower()
    assert "high-impact" in result.lower()


def test_soft_hyphens_removed():
    """Verifies that invisible soft hyphens (\u00AD) are removed without splitting words."""
    soft_sample = "algo\u00adrithms and archi\u00adtecture"
    result = join_hyphenated_line_breaks(soft_sample)

    assert result == "algorithms and architecture"
    assert "\u00ad" not in result


