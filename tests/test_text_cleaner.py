# 5. WHITESPACE COLLAPSING & LAYOUT CLEANING
# ==============================================================================

def test_whitespace_collapsing_doubled_spaces_and_non_breaking_spaces():
    """
    Verifies conversion of non-breaking spaces (\u00A0), zero-width characters,
    doubled spaces, and excessive line breaks.
    """
    messy_text = (
        "John\u00a0\u00a0Doe   \u200b\u200cSoftware   Engineer\n\n\n\n\n"
        "Education:    B.Tech in Computer Science  \n"
        "GPA:  3.9 / 4.0\n\n\n\n"
        "Skills:   Python,   Docker,   Kubernetes"
    )
    cleaned = collapse_whitespace(messy_text)

    # Doubled spaces collapsed
    assert "John Doe Software Engineer" in cleaned
    assert "Education: B.Tech in Computer Science" in cleaned
    assert "GPA: 3.9 / 4.0" in cleaned
    assert "Skills: Python, Docker, Kubernetes" in cleaned

    # Non-breaking and zero-width spaces eliminated
    assert "\u00a0" not in cleaned
    assert "\u200b" not in cleaned
    assert "\u200c" not in cleaned

    # No 3+ consecutive newlines
    assert "\n\n\n" not in cleaned


