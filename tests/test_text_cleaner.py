# 6. REPEATED HEADERS AND FOOTERS REMOVAL
# ==============================================================================

def test_repeated_headers_and_page_numbers_removed_across_pages():
    """
    Verifies that lines repeated across multiple pages (e.g. running headers,
    confidentiality notices, page numbers) are eliminated.
    """
    page1 = (
        "Alex Rivera\n"
        "alex@campus.edu | +1 (555) 019-2834\n"
        "Education: B.Tech Computer Science\n"
        "Algorithms, Database Management, Operating Systems\n"
        "Page 1 of 3"
    )
    page2 = (
        "Alex Rivera - Resume\n"
        "Work Experience:\n"
        "Software Engineering Intern at CloudTech\n"
        "Developed scalable API services in Go and PostgreSQL\n"
        "Page 2 of 3"
    )
    page3 = (
        "Alex Rivera - Resume\n"
        "Key Projects:\n"
        "Distributed KV Store with Raft consensus\n"
        "Autonomous Campus Navigation Mobile App\n"
        "Page 3 of 3"
    )

    cleaned = remove_repeated_headers_and_footers([page1, page2, page3])

    # Repeated running header should be removed from page 2 and 3
    assert cleaned.count("Alex Rivera - Resume") == 0

    # Running page numbers should be eliminated
    assert "Page 1 of 3" not in cleaned
    assert "Page 2 of 3" not in cleaned
    assert "Page 3 of 3" not in cleaned

    # Primary candidate info on page 1 must remain intact
    assert "Alex Rivera" in cleaned
    assert "alex@campus.edu" in cleaned
    assert "Work Experience:" in cleaned
    assert "Key Projects:" in cleaned


def test_form_feed_delimited_pages_strip_repeated_headers():
    """Verifies that multi-page text using form feeds (\\x0c) cleans repeated headers."""
    multi_page_text = (
        "Jane Smith\n"
        "jane@example.com\n"
        "Education: BS CS\n"
        "Page 1 of 2\x0c"
        "Jane Smith - Confidential\n"
        "Experience: Backend Developer at Stripe\n"
        "Page 2 of 2"
    )
    cleaned = normalize_resume_text(multi_page_text, store_raw=False)

    assert "Page 1 of 2" not in cleaned
    assert "Page 2 of 2" not in cleaned
    assert "Jane Smith" in cleaned
    assert "Backend Developer at Stripe" in cleaned


