    assert "Vue.js" in normalized
    assert "React.js" in normalized
    assert "CI/CD" in normalized
    assert "TCP/IP" in normalized
    assert "PL/SQL" in normalized
    assert "A/B testing" in normalized
    assert "Python 3.11" in normalized
    assert "Java 17" in normalized
    assert "HTML5" in normalized
    assert "CSS3" in normalized


