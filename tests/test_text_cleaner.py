# 4. BULLET GLYPHS NORMALIZATION
# ==============================================================================

def test_pua_and_exotic_bullets_mapped_to_standard():
    """
    Verifies that Private Use Area symbols and exotic Unicode bullets map to '• '.
    """
    raw_bullets = (
        "\uf0b7 Architected event-driven microservices\n"
        "➢ Optimized database queries reducing latency by 45%\n"
        "▪ Automated CI/CD pipeline using GitHub Actions\n"
        "‣ Built user-facing analytics dashboard in React\n"
        "★ Received Best Undergraduate Project award\n"
        "• Standard bullet point preserved cleanly"
    )
    cleaned = normalize_bullets(raw_bullets)

    assert "• Architected event-driven microservices" in cleaned
    assert "• Optimized database queries" in cleaned
    assert "• Automated CI/CD pipeline" in cleaned
    assert "• Built user-facing analytics dashboard" in cleaned
    assert "• Received Best Undergraduate Project award" in cleaned
    assert "• Standard bullet point preserved cleanly" in cleaned

    # Confirm PUA and exotic glyphs are removed
    assert "\uf0b7" not in cleaned
    assert "➢" not in cleaned
    assert "▪" not in cleaned
    assert "‣" not in cleaned
    assert "★" not in cleaned


def test_inline_bullet_separators_standardized():
    """Verifies that mid-line bullet separators between skills become ' • '."""
    inline_sample = "Skills: Python \uf0b7 Django \uf0b7 Docker \uf0b7 PostgreSQL"
    cleaned = normalize_bullets(inline_sample)

    assert cleaned == "Skills: Python • Django • Docker • PostgreSQL"


