class AIDisclaimerService:
    """Service to render standard and customizable AI disclaimers."""

    def __init__(self):
        self.presets = DISCLAIMER_PRESETS

    def get_disclaimer_data(self, category: str = "general_ai", lang: str = "en") -> Dict[str, Any]:
        """Returns structured metadata for a disclaimer preset with optional translation."""
        preset = self.presets.get(category, self.presets["general_ai"])
        short_text = preset["short_text"]
        if lang in preset.get("translations", {}):
            short_text = preset["translations"][lang]

        return {
            "category": category,
            "language": lang,
            "title": preset["title"],
            "badge": preset["badge"],
            "short_text": short_text,
            "full_text": preset["full_text"],
            "available_languages": ["en"] + list(preset.get("translations", {}).keys())
        }

    def render_banner_html(
        self,
        category: str = "general_ai",
        is_dismissible: bool = True,
        lang: str = "en",
        theme: str = "subtle"
    ) -> str:
        """
        Renders a responsive, accessible HTML banner component with an informational icon
        and expandable detail section.
        """
        data = self.get_disclaimer_data(category, lang=lang)
        escaped_title = html.escape(data["title"])
        escaped_badge = html.escape(data["badge"])
        escaped_short = html.escape(data["short_text"])
        escaped_full = html.escape(data["full_text"])

        dismiss_btn = ""
        if is_dismissible:
            dismiss_btn = """
            <button type="button" class="btn-close ms-auto" aria-label="Dismiss disclaimer" 
                    onclick="this.closest('.ai-disclaimer-banner').remove();" style="font-size: 0.75rem;">
            </button>
            """.strip()

        return f"""
<div class="ai-disclaimer-banner alert alert-info d-flex align-items-center py-2 px-3 mb-3 border-start border-4 border-info shadow-sm" role="region" aria-label="AI Content Disclaimer">
    <div class="ai-disclaimer-content w-100">
        <div class="d-flex align-items-center justify-content-between mb-1">
            <span class="badge bg-primary-subtle text-primary border border-primary-subtle me-2" style="font-size: 0.75rem;">
                {escaped_badge}
            </span>
            <strong class="text-dark small me-auto">{escaped_title}</strong>
            {dismiss_btn}
        </div>
        <div class="text-muted small" style="font-size: 0.82rem; line-height: 1.4;">
            {escaped_short}
            <details class="d-inline ms-1">
                <summary class="text-primary text-decoration-underline" style="cursor: pointer; display: inline;">Learn more</summary>
                <div class="p-2 mt-1 bg-white border rounded small text-secondary">
                    {escaped_full}
                </div>
            </details>
        </div>
    </div>
</div>
""".strip()

    def render_footnote_html(self, category: str = "general_ai", lang: str = "en") -> str:
        """Renders an unobtrusive footnote for reports, cards, and summaries."""
        data = self.get_disclaimer_data(category, lang=lang)
        return (
            f'<div class="ai-disclaimer-footnote text-muted small mt-2 pt-2 border-top" style="font-size: 0.75rem;">'
            f'<em>ℹ️ {html.escape(data["badge"])}: {html.escape(data["short_text"])}</em>'
            f'</div>'
        )

    def attach_disclaimer_to_payload(
        self,
        payload: Dict[str, Any],
        category: str = "general_ai",
        lang: str = "en"
    ) -> Dict[str, Any]:
        """
        Enriches an API response dictionary with structured disclaimer metadata and HTML snippet.
        """
        disclaimer_meta = self.get_disclaimer_data(category, lang=lang)
        enriched = dict(payload)
        enriched["ai_disclaimer"] = {
            **disclaimer_meta,
            "banner_html": self.render_banner_html(category, lang=lang),
            "footnote_html": self.render_footnote_html(category, lang=lang)
        }
        return enriched


ai_disclaimer_service = AIDisclaimerService()
