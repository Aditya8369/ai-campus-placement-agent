def resolve_output_locale(locale: str) -> Tuple[str, bool]:
    """Return a supported output locale and whether a fallback was required."""
    normalized = (locale or DEFAULT_OUTPUT_LOCALE).strip().lower()
    if normalized in SUPPORTED_OUTPUT_LOCALES:
        return normalized, False
    return DEFAULT_OUTPUT_LOCALE, normalized != DEFAULT_OUTPUT_LOCALE


def output_text(key: str, locale: str = DEFAULT_OUTPUT_LOCALE) -> str:
    """Resolve generated-output text with an English key fallback."""
    resolved, _ = resolve_output_locale(locale)
    return OUTPUT_TRANSLATIONS[resolved].get(
        key,
        OUTPUT_TRANSLATIONS[DEFAULT_OUTPUT_LOCALE].get(key, key),
    )
